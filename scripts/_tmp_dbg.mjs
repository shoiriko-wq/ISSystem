import puppeteer from 'puppeteer-core';
const BASE='https://127.0.0.1:3443', USER='T2026001', PASS='password123';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const browser=await puppeteer.launch({executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',headless:'new',ignoreHTTPSErrors:true,args:['--no-sandbox','--disable-setuid-sandbox','--disable-dev-shm-usage','--ignore-certificate-errors']});
const page=await browser.newPage();
page.on('pageerror',(e)=>console.log('[page js error]',e.message));
page.on('request',(r)=>{ if(r.url().includes('/api/bulletins')) console.log('REQ',r.method(),r.url()); });
page.on('response',async(r)=>{ if(r.url().includes('/api/bulletins') && r.url().includes('/read')) console.log('RES',r.status(),r.url(),await r.text().catch(()=>''));});
await page.setViewport({width:1280,height:900});
await page.goto(BASE+'/',{waitUntil:'networkidle2'});
await page.type('#login-userid',USER);await page.type('#login-password',PASS);
await page.evaluate(()=>window.handleLoginClick());
await page.waitForSelector('#app-container:not(.hidden)',{timeout:10000});
await page.evaluate(()=>document.querySelector('a[data-tab="dashboard"]')?.click());
await sleep(1500);
const ids=await page.evaluate(async()=>{const m=await import('/js/modules/bulletin.module.js');const c=m.bulletinsSnapshot();return c.map(b=>({id:b.id,unread:m.isUnreadForMe(b),target:m.targetDayOf(b),ack:b.ackStatus}));});
const target=ids.find(x=>x.unread);
console.log('TARGET',JSON.stringify(target));
await page.evaluate((bid)=>{
  document.getElementById('dash-pinned-bulletins').insertAdjacentHTML('beforeend','<button data-bulletin-read="'+bid+'">x</button>');
  document.querySelector('[data-bulletin-read="'+bid+'"]').click();
}, target.id);
await sleep(1600);
console.log('AFTER',JSON.stringify(await page.evaluate(()=>({side:document.getElementById('bulletin-unread-count')?.textContent.trim(),title:document.getElementById('bulletin-title-unread')?.textContent.trim(),dash:document.getElementById('dash-today-bulletin-unread')?.textContent.trim()}))));
await browser.close();
