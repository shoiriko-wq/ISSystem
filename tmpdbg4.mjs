import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
const find = [process.env.CHROME_PATH, '/usr/bin/google-chrome', '/usr/bin/chromium'].filter(Boolean).find((p) => fs.existsSync(p));
const b = await puppeteer.launch({ executablePath: find, headless: 'new', args: ['--no-sandbox', '--disable-setuid-sandbox', '--disable-dev-shm-usage', '--ignore-certificate-errors'] });
const page = await b.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.goto('https://127.0.0.1:3443/', { waitUntil: 'networkidle2' });
await page.type('#login-userid', 'T2026001');
await page.type('#login-password', 'password123');
await page.evaluate(() => window.handleLoginClick());
await page.waitForSelector('#app-container:not(.hidden)', { timeout: 10000 });
await new Promise((r) => setTimeout(r, 900));
await page.click('[data-tab="exam"]');
await new Promise((r) => setTimeout(r, 1600));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await page.click('[data-subtab="basic"]');
await sleep(900);
// basic card selects
const selPlan = await page.$('#exam-panel-basic .ui-exam-import-section');
const modePlan = await page.$('#exam-panel-basic .ui-exam-import-mode');
console.log('basic selects', !!selPlan, !!modePlan);
await selPlan.select('room');
await modePlan.select('current');
const resP = page.waitForResponse((r) => r.url().includes('/exam/import/template/room?mode=current'), { timeout: 8000 }).catch(() => null);
await page.click('#exam-panel-basic .ui-exam-import-template');
const roomRes = await resP;
console.log('roomRes', roomRes ? roomRes.status() : 'null', roomRes ? typeof roomRes.json : 'n/a');
const body = roomRes ? await roomRes.json().catch((e) => ({ err: e.message })) : null;
console.log('body-keys', Object.keys(body?.data || body || {}), 'row_count', (body?.data || body || {}).row_count, 'fileName', (body?.data || body || {}).fileName);
const csvText = (body?.data || body || {}).csvText || '';
console.log('first-lines', JSON.stringify(csvText.split('\r\n').slice(0, 3)));
const roomLines = csvText.split('\r\n').filter((l) => l.trim() !== '');
const parts = roomLines[1].split(',');
const roomName = parts[0];
const orig = Number(parts[1]);
parts[1] = '17';
roomLines[1] = parts.join(',');
fs.writeFileSync('/tmp/roomcur.csv', roomLines.join('\r\n'), 'utf8');
await (await page.$('#exam-panel-basic .ui-exam-import-file')).uploadFile('/tmp/roomcur.csv');
await sleep(1200);
console.log('summary', await page.evaluate(() => document.querySelector('#exam-panel-basic .ui-exam-import-summary')?.textContent));
await page.click('#exam-panel-basic .ui-exam-import-commit');
await sleep(2400);
console.log('toasts', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('#toast-container .toast')].map((t) => t.textContent.replace(/\s+/g, ' ')))));
import { query } from './src/utils/db.js';
const seats = await query('select seats from basic_rooms where name = $1', [roomName]);
console.log('db seats', JSON.stringify(seats.rows), 'roomName', roomName, 'orig', orig);
await query('update basic_rooms set seats = $1 where name = $2', [orig, roomName]);
await b.close();
process.exit(0);
